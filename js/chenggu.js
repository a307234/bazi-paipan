  function toLiangQian(total) {
    var liang = Math.floor(total);
    var qian = Math.round((total - liang) * 10);
    if (qian >= 10) { liang += 1; qian -= 10; }
    return { liang: liang, qian: qian, total: total, text: liang + "两" + qian + "钱" };
  }

  function poemKey(total) {
    var k = Math.min(57, Math.max(21, Math.round(total * 10)));
    return String(k);
  }

